// Each web photo exists as WebP at three long-edge sizes (800 / 1600 / 2200 px),
// e.g. public/photos-web/old-harry-800.webp. The original .jpg stays as fallback
// and as the social-sharing preview image.
const variantLongEdges = [800, 1600, 2200];

const buildSrcSet = (photo) => {
  const base = photo.src.replace(/\.jpg$/, '');
  const longEdge = Math.max(photo.width, photo.height);

  return variantLongEdges
    .map((edge) => {
      const scale = Math.min(1, edge / longEdge);
      return `${assetPath(`${base}-${edge}.webp`)} ${Math.round(photo.width * scale)}w`;
    })
    .join(', ');
};

export const photos = rawPhotos.map((photo) => ({
  ...photo,
  src: assetPath(photo.src),
  srcSet: buildSrcSet(photo),
}));
